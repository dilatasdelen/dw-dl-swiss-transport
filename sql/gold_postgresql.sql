-- KAN-66. Receiving tables for the approved Gold snapshot on PostgreSQL 15+.
BEGIN;

CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE gold.stop_event_analysis (
    weather_feed_version text,
    location_id text,
    weather_time_utc timestamptz,
    reference_feed_version text,
    stop_id text,
    parent_stop_id text,
    source_type text NOT NULL,
    event_key text NOT NULL,
    service_date date NOT NULL,
    source text,
    trip_id text,
    event_type text NOT NULL,
    didok text,
    source_canton text,
    boundary_release text,
    delay_seconds bigint,
    silver_input text NOT NULL,
    raw_object_key text,
    upstream_run_id text,
    prediction_signature text,
    effective_stop_sequence bigint,
    time_status text,
    selection_rule_version text,
    selection_window_start_utc timestamptz,
    selection_window_end_utc_exclusive timestamptz,
    is_final_published_prediction boolean,
    scheduled_time_utc timestamptz,
    reported_time_utc timestamptz,
    prediction_time_utc timestamptz,
    bpuic text,
    sloid text,
    bronze_object_key text,
    operator text,
    line_id text,
    transport_type text,
    is_cancelled boolean,
    is_additional boolean,
    is_passing boolean,
    stop_mapping_method text,
    study_canton_code text,
    stop_reference_input text,
    stop_boundary_release text,
    elevation_m double precision,
    elevation_source text,
    elevation_input text,
    elevation_response_key text,
    elevation_feed_version text,
    elevation_mapping_method text,
    weather_mapping_input text,
    weather_mapping_method text,
    temperature_2m_c double precision,
    precipitation_mm double precision,
    rain_mm double precision,
    snowfall_cm double precision,
    wind_speed_10m_kmh double precision,
    weather_code bigint,
    data_product text,
    model text,
    issued_hour_utc timestamptz,
    lead_hours bigint,
    retrieved_at_utc timestamptz,
    weather_bronze_object_key text,
    weather_processed_at_utc timestamptz,
    weather_silver_input text,
    missing_weather_location boolean NOT NULL,
    missing_weather boolean NOT NULL,
    missing_canton boolean NOT NULL,
    missing_elevation boolean NOT NULL,
    route_id text,
    CONSTRAINT stop_event_analysis_pkey
        PRIMARY KEY (source_type, event_key)
);

CREATE TABLE gold.weather_impact (
    source_type text NOT NULL,
    status_group text NOT NULL,
    delay_meaning text NOT NULL,
    event_type text NOT NULL,
    weather_group text NOT NULL,
    events_total bigint NOT NULL,
    observation_count bigint,
    cancelled_count bigint,
    median_delay_s bigint,
    p90_delay_s bigint,
    mean_delay_s double precision,
    severe_delay_rate double precision,
    date_range_start date,
    date_range_end date,
    grouping text NOT NULL,
    meets_minimum_observations boolean NOT NULL,
    research_question text NOT NULL,
    created_at_utc timestamptz NOT NULL,
    CONSTRAINT weather_impact_pkey
        PRIMARY KEY (source_type, status_group, delay_meaning, event_type, grouping, weather_group)
);

CREATE TABLE gold.stop_differences (
    source_type text NOT NULL,
    status_group text NOT NULL,
    delay_meaning text NOT NULL,
    event_type text NOT NULL,
    station_id text,
    canton text,
    elevation_group text NOT NULL,
    normal_events_total bigint,
    normal_observation_count bigint,
    normal_cancelled_count bigint,
    normal_median_delay_s bigint,
    normal_p90_delay_s bigint,
    normal_mean_delay_s double precision,
    normal_severe_delay_rate double precision,
    normal_date_range_start date,
    normal_date_range_end date,
    adverse_events_total bigint,
    adverse_observation_count bigint,
    adverse_cancelled_count bigint,
    adverse_median_delay_s bigint,
    adverse_p90_delay_s bigint,
    adverse_mean_delay_s double precision,
    adverse_severe_delay_rate double precision,
    adverse_date_range_start date,
    adverse_date_range_end date,
    median_delay_difference_s bigint,
    severe_rate_difference double precision,
    meets_minimum_observations boolean NOT NULL,
    difference_rank integer,
    research_question text NOT NULL,
    created_at_utc timestamptz NOT NULL,
    CONSTRAINT stop_differences_grain_key
        UNIQUE NULLS NOT DISTINCT (source_type, status_group, delay_meaning, event_type, station_id, canton, elevation_group)
);

CREATE TABLE gold.elevation_patterns (
    source_type text NOT NULL,
    status_group text NOT NULL,
    delay_meaning text NOT NULL,
    event_type text NOT NULL,
    elevation_group text NOT NULL,
    weather_category text NOT NULL,
    events_total bigint NOT NULL,
    observation_count bigint,
    cancelled_count bigint,
    median_delay_s bigint,
    p90_delay_s bigint,
    mean_delay_s double precision,
    severe_delay_rate double precision,
    date_range_start date,
    date_range_end date,
    meets_minimum_observations boolean NOT NULL,
    research_question text NOT NULL,
    created_at_utc timestamptz NOT NULL,
    CONSTRAINT elevation_patterns_pkey
        PRIMARY KEY (source_type, status_group, delay_meaning, event_type, elevation_group, weather_category)
);

CREATE TABLE gold.network_hotspots (
    source_type text NOT NULL,
    status_group text NOT NULL,
    delay_meaning text NOT NULL,
    event_type text NOT NULL,
    dimension text NOT NULL,
    dimension_value text,
    events_total bigint NOT NULL,
    observation_count bigint,
    cancelled_count bigint,
    median_delay_s bigint,
    p90_delay_s bigint,
    mean_delay_s double precision,
    severe_delay_rate double precision,
    date_range_start date,
    date_range_end date,
    meets_minimum_observations boolean NOT NULL,
    normal_observation_count bigint,
    adverse_observation_count bigint,
    normal_median_delay_s bigint,
    adverse_median_delay_s bigint,
    normal_severe_delay_rate double precision,
    adverse_severe_delay_rate double precision,
    median_delay_difference_s bigint,
    severe_rate_difference double precision,
    hotspot_rank integer,
    research_question text NOT NULL,
    created_at_utc timestamptz NOT NULL,
    CONSTRAINT network_hotspots_grain_key
        UNIQUE NULLS NOT DISTINCT (source_type, status_group, delay_meaning, event_type, dimension, dimension_value)
);

CREATE INDEX stop_event_analysis_service_date_idx
    ON gold.stop_event_analysis USING brin (service_date);

COMMENT ON COLUMN gold.stop_event_analysis.route_id IS
    'GTFS route ID within reference_feed_version. NULL for legacy Parquet and events without a GTFS route ID.';

COMMIT;
